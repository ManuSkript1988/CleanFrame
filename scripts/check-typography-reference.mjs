// Typography regression check. Development only; never contacts a TV.
// With every text area at Standard (Manrope) and 100 %, each visible text element must match
// the reference commit in scripts/typography-reference.json: font, size, weight, spacing, line
// height and position. Both versions run in the same Chromium with the same fonts; the
// reference app/ files are served straight from Git objects. Every difference must be covered
// by a documented exception, otherwise the check fails.
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { openPreview, root } from './browser.mjs';

const config = JSON.parse(readFileSync(root + 'scripts/typography-reference.json', 'utf8'));
const REF = config.reference.commit;
try { execFileSync('git', ['cat-file', '-e', REF + '^{commit}'], { cwd: root, stdio: 'ignore' }); }
catch { console.error('Reference commit ' + REF + ' is not in this clone. Fetch the full history and run again.'); process.exit(1); }

const KEY = 'cleanframe.home.v1';
const TIME = new Date(2026, 10, 18, 9, 5, 0);
const TYPES = { html: 'text/html; charset=utf-8', js: 'text/javascript; charset=utf-8', css: 'text/css; charset=utf-8', json: 'application/json', svg: 'image/svg+xml', png: 'image/png', jpg: 'image/jpeg', webp: 'image/webp', woff2: 'font/woff2', ttf: 'font/ttf', txt: 'text/plain' };
// Generated by the preview from the local font overlay; not part of app/ in Git.
const GENERATED = path => path === 'assets/font-catalog.js' || path === 'assets/private-fonts.css' || path.startsWith('assets/private-fonts/');
const blobs = new Map();
function referenceFile(path) {
  if (!blobs.has(path)) {
    try { blobs.set(path, execFileSync('git', ['show', REF + ':app/' + path], { cwd: root, maxBuffer: 64 << 20, stdio: ['ignore', 'pipe', 'ignore'] })); }
    catch { blobs.set(path, null); }
  }
  return blobs.get(path);
}

const baseline = (patch = {}) => ({ dock: ['stremio', 'netflix', 'disneyplus', 'youtube', 'appletv', 'primevideo', 'abciview', 'sbs', 'applemusic'], wallpaper: 'misty', mode: 'fixed', lastApp: 'netflix', theme: 'shore', ...patch });
const LOOKS = {
  'dock-photo': baseline(),
  'list-photo': baseline({ look: { bg: 'photo', layout: 'list', apps: 'both', controls: 'both', focus: 'glass', material: 'soft' } }),
  'list-dark': baseline({ look: { bg: 'dark', layout: 'list', apps: 'text', controls: 'text', focus: 'type', material: 'soft' } }),
  'dock-light': baseline({ look: { bg: 'light', layout: 'dock', apps: 'icons', controls: 'icons', focus: 'type', material: 'soft' } })
};
// Each scene: a saved look and the steps that reach it. The same steps run on both versions.
const SCENES = [
  { id: 'home-dock-photo', look: 'dock-photo', steps: [] },
  { id: 'home-list-photo', look: 'list-photo', steps: [] },
  { id: 'home-list-dark', look: 'list-dark', steps: [] },
  { id: 'home-dock-light', look: 'dock-light', steps: [] },
  { id: 'home-utilities', look: 'dock-photo', steps: [['nav', 'up']] },
  { id: 'leave-dialog', look: 'list-dark', steps: [['nav', 'back']] },
  { id: 'all-apps', look: 'dock-photo', steps: [['scene', 'apps']] },
  { id: 'editor', look: 'list-dark', steps: [['scene', 'editor']] },
  { id: 'settings', look: 'dock-photo', steps: [['scene', 'settings']] },
  { id: 'settings-dark', look: 'list-dark', steps: [['scene', 'settings']] },
  { id: 'settings-background', look: 'dock-photo', steps: [['scene', 'settings'], ['activate', 'settings.group.background']] },
  { id: 'settings-layout', look: 'dock-photo', steps: [['scene', 'settings'], ['activate', 'settings.group.layout']] },
  { id: 'settings-focus', look: 'dock-photo', steps: [['scene', 'settings'], ['activate', 'settings.group.focus']] },
  { id: 'settings-samsung', look: 'list-dark', steps: [['scene', 'settings'], ['activate', 'settings.group.samsung']] }
];

function capture() {
  const stage = document.getElementById('stage'), sr = stage.getBoundingClientRect(), k = 1920 / sr.width, out = [], seen = new Set(), count = {};
  const shown = el => { for (let e = el; e; e = e.parentElement) { const s = getComputedStyle(e); if (s.display === 'none' || s.visibility === 'hidden' || Number(s.opacity) === 0 || e.hidden) return false; } const r = el.getBoundingClientRect(); return r.width > 0 && r.height > 0; };
  // Stable path: ids and classes up to the stage; transient state classes (is-*) are left out.
  // span.clock-block only wraps the clock and its new date; leaving it out of the path lets the
  // clock itself be compared with the reference instead of counting as removed and added.
  const path = el => { const parts = []; for (let e = el; e && e !== stage; e = e.parentElement) if (!e.classList.contains('clock-block')) parts.unshift(e.id ? '#' + e.id : e.tagName.toLowerCase() + [...e.classList].filter(c => !/^is-/.test(c)).map(c => '.' + c).join('')); return parts.join(' > '); };
  const r5 = v => Math.round(v * k * 2) / 2;
  const walker = document.createTreeWalker(stage, NodeFilter.SHOW_TEXT);
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    const el = node.parentElement, text = node.textContent.replace(/\s+/g, ' ').trim();
    if (!text || seen.has(el) || !shown(el)) continue;
    seen.add(el);
    const s = getComputedStyle(el), r = el.getBoundingClientRect();
    let key = path(el) + ' "' + el.textContent.replace(/\s+/g, ' ').trim().slice(0, 60) + '"';
    count[key] = (count[key] || 0) + 1; if (count[key] > 1) key += ' #' + count[key];
    out.push({ key, family: s.fontFamily.split(',')[0].replace(/["']/g, '').trim(), size: s.fontSize, weight: s.fontWeight, spacing: s.letterSpacing, line: s.lineHeight,
      x: r5(r.left - sr.left), y: r5(r.top - sr.top), w: r5(r.width), h: r5(r.height) });
  }
  // Icons and app marks sit beside text, so their positions are compared too (no font values).
  for (const el of stage.querySelectorAll('svg, img, .mark, .setting-mark')) {
    if (seen.has(el) || !shown(el)) continue;
    seen.add(el);
    const r = el.getBoundingClientRect();
    let key = path(el) + ' [graphic]';
    count[key] = (count[key] || 0) + 1; if (count[key] > 1) key += ' #' + count[key];
    out.push({ key, family: '', size: '', weight: '', spacing: '', line: '', x: r5(r.left - sr.left), y: r5(r.top - sr.top), w: r5(r.width), h: r5(r.height) });
  }
  return out;
}

async function measure(preview, version, sceneDef) {
  const page = await preview.browser.newPage({ viewport: { width: 1920, height: 1080 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.clock.setFixedTime(TIME);
  await page.addInitScript({ path: root + 'scripts/preview/tv-mock.js' });
  await page.addInitScript(([key, seed]) => {
    if (!sessionStorage.getItem('__seeded')) { localStorage.setItem(key, JSON.stringify(seed)); sessionStorage.setItem('__seeded', '1'); }
    window.CleanFrameTVMock.install({});
  }, [KEY, LOOKS[sceneDef.look]]);
  if (version === 'reference') await page.route('**/home/**', route => {
    const path = decodeURIComponent(new URL(route.request().url()).pathname.slice('/home/'.length)) || 'index.html';
    if (GENERATED(path)) return route.continue();
    const body = referenceFile(path);
    if (body === null) return route.fulfill({ status: 404, body: '' });
    return route.fulfill({ status: 200, body, contentType: TYPES[path.split('.').pop()] || 'application/octet-stream' });
  });
  await page.goto(preview.baseURL + '/home/', { waitUntil: 'load' });
  const ready = () => page.waitForFunction(() => window.ShoreQA && ShoreQA.ready && ShoreQA.ready(), null, { timeout: 15000 });
  await ready(); await page.waitForLoadState('networkidle');
  for (const [method, arg] of sceneDef.steps) {
    await page.evaluate(([m, a]) => m === 'nav' ? ShoreQA.nav([a]) : ShoreQA[m](a), [method, arg]);
    await page.waitForFunction(() => window.ShoreQA.where && !ShoreQA.state().pending, null, { timeout: 15000 });
  }
  await page.waitForLoadState('networkidle');
  // Let focus and crossfade transitions settle before measuring.
  await page.waitForTimeout(600);
  const items = await page.evaluate(capture);
  const where = await page.evaluate(() => ShoreQA.where());
  await page.close();
  return { items, errors, where };
}

function compare(scene, ref, cur) {
  const diffs = [], byKey = list => new Map(list.map(i => [i.key, i]));
  const a = byKey(ref), b = byKey(cur);
  for (const [key, r] of a) {
    const c = b.get(key);
    if (!c) { diffs.push({ scene, kind: 'removed', key, reference: r }); continue; }
    const changed = ['family', 'size', 'weight', 'spacing', 'line', 'x', 'y', 'w', 'h'].filter(p => r[p] !== c[p]);
    if (changed.length) diffs.push({ scene, kind: 'changed', key, props: changed, reference: Object.fromEntries(changed.map(p => [p, r[p]])), current: Object.fromEntries(changed.map(p => [p, c[p]])) });
  }
  for (const [key, c] of b) if (!a.has(key)) diffs.push({ scene, kind: 'added', key, current: c });
  return diffs;
}

// An exception covers a difference when scene, kind, key and (for changes) every changed
// property match. `props` lists the properties an exception allows to change.
function covering(diff) {
  return config.exceptions.find(e => (!e.scenes || e.scenes.includes(diff.scene)) && e.kinds.includes(diff.kind) && new RegExp(e.key).test(diff.key)
    && (diff.kind !== 'changed' || diff.props.every(p => (e.props || []).includes(p))));
}

const preview = await openPreview({ publicFonts: true });
const report = { scope: 'Reference ' + REF + ' vs working tree, Chromium, Standard at 100 %; no TV contacted.', scenes: {}, uncovered: [], covered: [], unusedExceptions: [], pageErrors: [] };
try {
  for (const scene of SCENES) {
    const ref = await measure(preview, 'reference', scene), cur = await measure(preview, 'current', scene);
    if (ref.errors.length || cur.errors.length) report.pageErrors.push({ scene: scene.id, reference: ref.errors, current: cur.errors });
    const diffs = compare(scene.id, ref.items, cur.items);
    report.scenes[scene.id] = { elements: ref.items.length, where: { reference: ref.where, current: cur.where }, differences: diffs.length };
    for (const d of diffs) { const e = covering(d); if (e) report.covered.push({ exception: e.id, ...d }); else report.uncovered.push(d); }
    console.log(scene.id + ': ' + ref.items.length + ' elements (text, icons, marks), ' + diffs.length + ' difference(s)');
  }
} finally { await preview.close(); }
report.unusedExceptions = config.exceptions.filter(e => !report.covered.some(c => c.exception === e.id)).map(e => e.id);
mkdirSync(root + '.local/qa', { recursive: true });
writeFileSync(root + '.local/qa/typography-reference.json', JSON.stringify(report, null, 2) + '\n');
const failures = report.uncovered.length + report.unusedExceptions.length + report.pageErrors.length;
for (const d of report.uncovered) console.log('UNCOVERED ' + d.scene + ' ' + d.kind + ' ' + d.key + (d.props ? ' ' + JSON.stringify({ reference: d.reference, current: d.current }) : ''));
for (const id of report.unusedExceptions) console.log('UNUSED EXCEPTION ' + id);
for (const p of report.pageErrors) console.log('PAGE ERROR ' + JSON.stringify(p));
console.log(report.covered.length + ' covered by documented exceptions; ' + failures + ' failure(s). Report: .local/qa/typography-reference.json');
process.exit(failures ? 1 : 0);
